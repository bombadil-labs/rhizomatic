#!/usr/bin/env python3
"""Generate src/Rhizomatic/UnicodeTables.hs from the host Python's unicodedata.

The witness validates NFC (SPEC-1 §4.1: validated at the boundary, never repaired)
by full normalize-and-compare, which needs three tables:

  ccc     canonical combining classes (nonzero only, as ranges)
  decomp  canonical (untagged) decomposition mappings, non-Hangul
  comp    primary composites — pairs that recompose under NFC

Primary composites are derived without CompositionExclusions.txt: a code point X
with a 2-char canonical decomposition is a primary composite iff NFC(NFD(X)) == X
(exclusions — script-specific, post-composition, singletons, non-starter
decompositions — are exactly the X for which recomposition does not happen).
Hangul is algorithmic in the Haskell code and skipped here.

Table provenance is pinned in the generated header (ERRATA D15: NFC per the
witness's own tables). Rerun only deliberately; the output is committed.
"""

import sys
import unicodedata

MAX_CP = 0x110000
HANGUL_S, HANGUL_COUNT = 0xAC00, 11172


def main() -> None:
    ccc_ranges = []  # (lo, hi, ccc)
    for cp in range(MAX_CP):
        c = unicodedata.combining(chr(cp))
        if c == 0:
            continue
        if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == c:
            ccc_ranges[-1] = (ccc_ranges[-1][0], cp, c)
        else:
            ccc_ranges.append((cp, cp, c))

    decomp = []  # (cp, [cp...])
    comp = []  # (first, second, composite)
    for cp in range(MAX_CP):
        if HANGUL_S <= cp < HANGUL_S + HANGUL_COUNT:
            continue
        ch = chr(cp)
        d = unicodedata.decomposition(ch)
        if not d or d.startswith("<"):
            continue
        parts = [int(p, 16) for p in d.split()]
        decomp.append((cp, parts))
        if len(parts) == 2 and unicodedata.normalize("NFC", unicodedata.normalize("NFD", ch)) == ch:
            comp.append((parts[0], parts[1], cp))

    with open(sys.argv[1] if len(sys.argv) > 1 else "../src/Rhizomatic/UnicodeTables.hs", "w") as f:
        w = f.write
        w("-- | GENERATED by gen/gen_unicode_tables.py — do not edit by hand.\n")
        w(f"-- Source: Python {sys.version.split()[0]} unicodedata, UCD {unicodedata.unidata_version}.\n")
        w("-- See ERRATA D15 (SPEC-1): NFC validation runs against the witness's own tables.\n")
        w("module Rhizomatic.UnicodeTables (cccRanges, decompositions, primaryComposites) where\n\n")
        w("-- | (lo, hi, ccc) for every code point with nonzero canonical combining class.\n")
        w("cccRanges :: [(Int, Int, Int)]\n")
        w("cccRanges =\n  [ " + "\n  , ".join(f"({lo},{hi},{c})" for lo, hi, c in ccc_ranges) + "\n  ]\n\n")
        w("-- | Canonical decomposition mappings (untagged, non-Hangul), unclosed.\n")
        w("decompositions :: [(Int, [Int])]\n")
        w("decompositions =\n  [ " + "\n  , ".join(f"({cp},{parts})" for cp, parts in decomp) + "\n  ]\n\n")
        w("-- | (first, second, composite) — canonical pairs that recompose under NFC.\n")
        w("primaryComposites :: [(Int, Int, Int)]\n")
        w("primaryComposites =\n  [ " + "\n  , ".join(f"({a},{b},{x})" for a, b, x in comp) + "\n  ]\n")

    print(f"ccc ranges: {len(ccc_ranges)}, decompositions: {len(decomp)}, composites: {len(comp)}")


if __name__ == "__main__":
    main()
